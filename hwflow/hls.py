"""Generate the Vitis HLS Tcl from build.yaml, run it, and collect IP, hw.h and the csynth report."""
 
 
import json
import shutil
import subprocess
import time
import xml.etree.ElementTree as ET
from pathlib import Path
 
PROJECT = "hls_prj"
SOLUTION = "solution1"
 
 
class HlsError(RuntimeError):
    pass
 
 
def _brace(value):
    return "{" + str(value) + "}"
 
 
STEPS = ("csim", "csynth", "cosim", "export")
 
 
def generate_tcl(cfg, steps=None, fresh=True):
    """HLS Tcl for the given steps (default: build.yaml steps).
 
    fresh: create the project from scratch (open_project/open_solution -reset, add all files).
    Otherwise reopen the existing project so earlier results (e.g. csynth before export) stay.
    """
    steps = cfg.steps if steps is None else steps
    if not fresh:
        lines = ["# generated by hwflow from " + str(cfg.path) + f" (steps: {' '.join(steps)})",
                 f"open_project {PROJECT}", f"open_solution {SOLUTION} -flow_target vivado"]
        return "\n".join(lines + _step_lines(cfg, steps)) + "\n"
    includes = " ".join(f"-I{p}" for p in cfg.include_dirs)
    cflags = " ".join(x for x in (includes, cfg.cflags) if x)
    tb_cflags = " ".join(x for x in (includes, cfg.tb_cflags) if x)
    lines = [
        "# generated by hwflow from " + str(cfg.path),
        f"open_project -reset {PROJECT}",
        f"set_top {cfg.top}",
    ]
    lines += [f"add_files -cflags {_brace(cflags)} {_brace(p)}" for p in cfg.sources]
    lines += [f"add_files {_brace(p)}" for p in cfg.headers]
    lines += [f"add_files -tb -cflags {_brace(tb_cflags)} {_brace(p)}" for p in cfg.testbench + cfg.tb_data]
    lines += [
        f"open_solution -reset {SOLUTION} -flow_target vivado",
        f"set_part {_brace(cfg.part)}",
        f"create_clock -period {cfg.clock_period_ns:.4f} -name default",
    ]
    lines += [f"source {_brace(p)}" for p in cfg.hls_directives]
    lines += [cfg.fill(t) for t in cfg.extra_tcl]
    return "\n".join(lines + _step_lines(cfg, steps)) + "\n"
 
 
def _step_lines(cfg, steps):
    argv = cfg.fill(cfg.tb_args)
    argv_opt = f" -argv {_brace(argv)}" if argv else ""
    lines = []
    if "csim" in steps:
        lines.append(f"csim_design{argv_opt}")
    if "csynth" in steps:
        lines.append("csynth_design")
    if "cosim" in steps:
        lines.append(f"cosim_design{argv_opt}")
    if "export" in steps:
        lines.append("export_design -format ip_catalog")
    lines.append("exit")
    return lines
 
 
def parse_csynth_report(path):
    """Estimated clock, latency and resources from solution1/syn/report/csynth.xml."""
    root = ET.parse(str(path)).getroot()
 
    def text(xpath):
        node = root.find(xpath)
        return node.text.strip() if node is not None and node.text else None
 
    def number(xpath):
        value = text(xpath)
        try:
            return float(value) if "." in value else int(value)
        except (TypeError, ValueError):
            return value
 
    resources = {}
    for name in ("BRAM_18K", "DSP", "FF", "LUT", "URAM"):
        used = number(f"./AreaEstimates/Resources/{name}")
        avail = number(f"./AreaEstimates/AvailableResources/{name}")
        if used is not None:
            resources[name] = {"used": used, "available": avail}
    return {
        "target_clock_ns": number("./UserAssignments/TargetClockPeriod"),
        "estimated_clock_ns": number("./PerformanceEstimates/SummaryOfTimingAnalysis/EstimatedClockPeriod"),
        "latency_cycles_best": number("./PerformanceEstimates/SummaryOfOverallLatency/Best-caseLatency"),
        "latency_cycles_worst": number("./PerformanceEstimates/SummaryOfOverallLatency/Worst-caseLatency"),
        "interval_min": number("./PerformanceEstimates/SummaryOfOverallLatency/Interval-min"),
        "resources": resources,
    }
 
 
def collect(cfg, hls_dir):
    sol = hls_dir / PROJECT / SOLUTION
    out = {}
    report = sol / "syn" / "report" / "csynth.xml"
    if report.exists():
        out["csynth"] = parse_csynth_report(report)
        shutil.copy2(report, hls_dir / "csynth.xml")
    if "export" in cfg.steps:
        ip_dir = sol / "impl" / "ip"
        if not (ip_dir / "component.xml").exists():
            raise HlsError(f"export finished but {ip_dir}/component.xml is missing")
        out["ip_repo"] = str(ip_dir)
        out["ip_zip"] = [str(p) for p in sorted(ip_dir.glob("*.zip"))]
        headers = sorted((sol / "impl" / "misc" / "drivers").glob("*/src/x*_hw.h"))
        if headers:
            out["hw_h"] = str(headers[0])
    return out
 
 
def run_hls(cfg, build_dir, force=False, log=print):
    hls_dir = Path(build_dir) / "hls"
    summary_path = hls_dir / "hls_summary.json"
    if summary_path.exists() and not force:
        summary = json.loads(summary_path.read_text())
        if summary.get("status") == "ok":
            log(f"hls: up to date ({hls_dir})")
            check_resources(cfg, summary, log)
            return summary
    hls_dir.mkdir(parents=True, exist_ok=True)
    tcl = hls_dir / "run_hls.tcl"
    tcl.write_text(generate_tcl(cfg), encoding="utf-8")
    log_path = hls_dir / "vitis_hls.log"
    cmd = [cfg.vitis_hls, "-f", str(tcl)]
    log(f"hls: {' '.join(cmd)}  (log: {log_path})")
    start = time.time()
    with open(log_path, "w", encoding="utf-8") as handle:
        try:
            proc = subprocess.run(cmd, cwd=hls_dir, stdout=handle, stderr=subprocess.STDOUT)
        except FileNotFoundError as exc:
            raise HlsError(f"'{cfg.vitis_hls}' not found; source the Vitis HLS settings64.sh or set tools.vitis_hls") from exc
    summary = {"status": "error", "returncode": proc.returncode, "seconds": round(time.time() - start, 1),
               "tcl": str(tcl), "log": str(log_path), "steps": cfg.steps, "top": cfg.top,
               "clock_mhz": cfg.clock_mhz, "part": cfg.part}
    errors = [l.strip() for l in log_path.read_text(errors="replace").splitlines() if l.startswith("ERROR:")]
    summary["errors"] = errors[:20]
    try:
        if proc.returncode != 0:
            raise HlsError(f"vitis_hls exited with {proc.returncode}; first errors: {errors[:3]}")
        summary.update(collect(cfg, hls_dir))
        summary["status"] = "ok"
    finally:
        summary_path.write_text(json.dumps(summary, indent=2), encoding="utf-8")
    est = summary.get("csynth") or {}
    log(f"hls: ok in {summary['seconds']} s, est. clock {est.get('estimated_clock_ns')} ns, "
        f"latency {est.get('latency_cycles_best')}..{est.get('latency_cycles_worst')} cycles")
    check_resources(cfg, summary, log)
    return summary
 
 
def run_step(cfg, build_dir, step, log=print):
    """Run one HLS step on its own (python3 -m hwflow csim|csynth|cosim|export build.yaml).
 
    The first step creates the project; later steps reopen it, so csynth results are kept
    for cosim/export. hls_summary.json is updated after csynth and export, and becomes
    status ok once the IP is exported, so `vivado` can follow.
    """
    hls_dir = Path(build_dir) / "hls"
    hls_dir.mkdir(parents=True, exist_ok=True)
    sol = hls_dir / PROJECT / SOLUTION
    report = sol / "syn" / "report" / "csynth.xml"
    if step in ("cosim", "export") and not report.exists():
        raise HlsError(f"{step} needs a synthesized design; run csynth first")
    fresh = not (sol / f"{SOLUTION}.aps").exists() and not (hls_dir / PROJECT / "hls.app").exists()
    tcl = hls_dir / f"run_{step}.tcl"
    tcl.write_text(generate_tcl(cfg, [step], fresh=fresh), encoding="utf-8")
    log_path = hls_dir / f"vitis_hls_{step}.log"
    cmd = [cfg.vitis_hls, "-f", str(tcl)]
    log(f"hls {step}: {' '.join(cmd)}  (log: {log_path})")
    start = time.time()
    with open(log_path, "w", encoding="utf-8") as handle:
        try:
            proc = subprocess.run(cmd, cwd=hls_dir, stdout=handle, stderr=subprocess.STDOUT)
        except FileNotFoundError as exc:
            raise HlsError(f"'{cfg.vitis_hls}' not found; source the Vitis HLS settings64.sh or set tools.vitis_hls") from exc
    seconds = round(time.time() - start, 1)
    errors = [l.strip() for l in log_path.read_text(errors="replace").splitlines() if l.startswith("ERROR:")]
    if proc.returncode != 0:
        raise HlsError(f"{step} failed (vitis_hls exit {proc.returncode}); first errors: {errors[:3]}; see {log_path}")
    log(f"hls {step}: ok in {seconds} s")
 
    summary_path = hls_dir / "hls_summary.json"
    summary = json.loads(summary_path.read_text()) if summary_path.exists() else {}
    if fresh:
        summary = {}
    summary.update({"top": cfg.top, "clock_mhz": cfg.clock_mhz, "part": cfg.part})
    done = [s for s in summary.get("steps_done", []) if s != step] + [step]
    summary["steps_done"] = done
    if step == "csynth":
        summary.pop("ip_repo", None)        # a new synthesis invalidates an earlier export
        summary["steps_done"] = [s for s in done if s != "export"]
    if step in ("csynth", "export"):
        export_cfg = cfg if step == "export" else _NoExport(cfg)
        summary.update(collect(export_cfg, hls_dir))
    summary["status"] = "ok" if summary.get("ip_repo") else "partial"
    summary_path.write_text(json.dumps(summary, indent=2), encoding="utf-8")
    if step == "csynth":
        est = summary.get("csynth") or {}
        log(f"hls csynth: est. clock {est.get('estimated_clock_ns')} ns, "
            f"latency {est.get('latency_cycles_best')}..{est.get('latency_cycles_worst')} cycles")
        check_resources(cfg, summary, log)
    return summary
 
 
class _NoExport:
    """cfg view whose steps leave out export, so collect() does not look for the IP yet."""
 
    def __init__(self, cfg):
        self._cfg = cfg
        self.steps = [s for s in cfg.steps if s != "export"]
 
    def __getattr__(self, name):
        return getattr(self._cfg, name)
 
 
def check_resources(cfg, summary, log=print):
    """Stop before Vivado when the csynth estimate exceeds hls_max_util_pct of the device.
 
    The limit is checked on every call (also for a cached HLS run), so raising it in
    build.yaml does not need a new HLS run. An estimated clock slower than the target
    is only a warning: Vivado's WNS check decides timing.
    """
    est = summary.get("csynth") or {}
    limits = cfg.hls_max_util_pct
    over = []
    for name, item in (est.get("resources") or {}).items():
        used, avail = item.get("used"), item.get("available")
        if not isinstance(used, (int, float)) or not isinstance(avail, (int, float)) or avail <= 0:
            continue
        pct = 100.0 * used / avail
        item["util_pct"] = round(pct, 2)
        limit = limits.get(name, limits.get("default", 100.0)) if isinstance(limits, dict) else limits
        if limit is not None and pct > float(limit):
            over.append(f"{name} {used}/{avail} ({pct:.1f}% > {float(limit):g}%)")
    target, clock = est.get("target_clock_ns"), est.get("estimated_clock_ns")
    if isinstance(target, (int, float)) and isinstance(clock, (int, float)) and clock > target:
        log(f"hls: WARNING estimated clock {clock} ns is slower than the target {target} ns")
    if over:
        raise HlsError("csynth estimate exceeds the resource limit, Vivado not started: " + ", ".join(over)
                       + " (reduce unroll/partition, or raise hls_max_util_pct in build.yaml)")
 